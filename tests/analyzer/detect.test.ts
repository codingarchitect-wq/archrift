import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import { detectProject } from '../../src/analyzer/detect.ts'
import { copyFixture } from '../helpers/fixtures.ts'

const dirs: string[] = []
afterEach(() => {
  for (const d of dirs.splice(0)) fs.rmSync(d, { recursive: true, force: true })
})

/** A project made of these files (path → content), outside any git repository: found by walking it. */
function project(files: Record<string, string>): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'archrift-detect-'))
  dirs.push(root)
  for (const [rel, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true })
    fs.writeFileSync(path.join(root, rel), content)
  }
  return root
}

describe('detecting a project', () => {
  it('reads a Vite app: its stack, the script its page loads, generated code, static files and a copied-in kit', () => {
    const root = copyFixture('vite-app')
    dirs.push(root)
    const d = detectProject(root)
    expect(d.stack).toEqual(['TypeScript', 'JavaScript', 'React', 'Vite', 'Tailwind CSS', 'Vitest', 'shadcn/ui'])
    expect(d.tsconfig).toBeUndefined()
    expect(d.exclude).toEqual([
      { glob: 'src/generated/**', why: 'generated (its header says so)' },
      { glob: 'public/**', why: 'static files the browser loads as they are' },
    ])
    // index.html's script, the file a package script runs, the config files
    expect(d.entrypoints).toEqual(['src/main.tsx', 'scripts/seed.ts', '*.config.{ts,mts,cts,js,mjs,cjs}'])
    // components.json's ui alias, through the tsconfig's paths (a tsconfig with comments)
    expect(d.vendored).toEqual([{ glob: 'src/components/ui/**', what: 'shadcn/ui components, copied in' }])
    expect(d.notes).toEqual([expect.stringMatching(/^dependencies not installed in the project folder \(no node_modules\)/)])
    expect(d.name).toBe(path.basename(root))
  })

  it('reads a Next.js app: the files the framework loads, and the Prisma client wherever the schema writes it', () => {
    const root = project({
      'package.json': JSON.stringify({ dependencies: { next: '16', react: '19', '@prisma/client': '7' } }),
      'node_modules/.keep': '',
      'tsconfig.json': '{}',
      'src/app/page.tsx': 'export default function Page() { return null }',
      'src/proxy.ts': 'export function proxy() {}',
      'prisma/schema.prisma': 'generator client {\n  provider = "prisma-client"\n  output   = "../src/generated/prisma"\n}\n',
      'src/lib/db.ts': 'export const db = 1',
    })
    const d = detectProject(root)
    expect(d.stack).toEqual(['TypeScript', 'Next.js', 'React', 'Prisma'])
    expect(d.entrypoints).toEqual([
      'src/app/**/{page,layout,template,loading,error,global-error,not-found,default,route,robots,sitemap,manifest,opengraph-image,twitter-image,icon,apple-icon}.{ts,tsx,js,jsx}',
      'src/proxy.ts',
    ])
    expect(d.exclude).toEqual([{ glob: 'src/generated/prisma/**', why: 'the Prisma client, generated' }])
    expect(d.notes).toEqual([])
  })

  it('reads a monorepo: each package’s tsconfig, its own tests and entries, the packages not installed, the languages it can’t read', () => {
    const root = project({
      'package.json': JSON.stringify({ private: true, workspaces: ['apps/*'] }),
      'apps/api/package.json': JSON.stringify({ main: 'dist/index.js', dependencies: { express: '5' } }),
      'apps/api/tsconfig.json': '{}',
      'apps/api/src/index.ts': 'export const app = 1',
      'apps/api/tests/app.test.ts': '',
      'apps/web/package.json': JSON.stringify({ dependencies: { react: '19' }, scripts: { gen: 'node ./tools/gen.mjs' } }),
      'apps/web/node_modules/.keep': '',
      'apps/web/tsconfig.json': '{}',
      'apps/web/tools/gen.mjs': '',
      'sdk/python/client.py': '',
      'sdk/python/models.py': '',
    })
    const d = detectProject(root)
    expect(d.tsconfig).toEqual(['apps/api/tsconfig.json', 'apps/web/tsconfig.json'])
    expect(d.tests).toContain('apps/api/tests/**')
    // main points at the build output: the source index stands for it
    expect(d.entrypoints).toEqual(['apps/api/src/index.ts', 'apps/web/tools/gen.mjs'])
    expect(d.notes).toEqual([
      "not read (archrift doesn't know these languages): Python 2 files",
      expect.stringMatching(/^dependencies not installed in apps\/api \(no node_modules\)/),
    ])
  })

  it('folds generated files into the highest folder holding nothing else, and names a lone one by itself', () => {
    const header = '// Code generated by protoc. DO NOT EDIT.\n'
    const root = project({
      'tsconfig.json': '{}',
      'src/gen/a.ts': header,
      'src/gen/deep/b.ts': header,
      'src/api/client.ts': '/* This file was automatically generated. */\n',
      'src/api/handler.ts': 'export const h = 1',
    })
    expect(detectProject(root).exclude).toEqual([
      { glob: 'src/api/client.ts', why: 'generated (its header says so)' },
      { glob: 'src/gen/**', why: 'generated (its header says so)' },
    ])
  })
})
