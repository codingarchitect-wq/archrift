import { describe, expect, it } from 'vitest'
import { parseDdl } from '../../src/analyzer/infra/ddl.ts'
import { SqlSchema, migrationOrder } from '../../src/analyzer/plugins/schema-sql.ts'
import type { TableMeta } from '../../src/core/model.ts'

/** A table's columns as `name type flags`, the way an ERD lists them. */
const columns = (t: TableMeta) =>
  t.columns.map(c => [c.name, c.type ?? '', ...(['pk', 'nullable', 'unique', 'generated', 'virtual'] as const).filter(f => c[f]), c.target ? `-> ${c.target}` : ''].filter(Boolean).join(' '))

describe('SQL DDL', () => {
  const ops = (sql: string, engine = 'mysql') => parseDdl(sql, engine)
  const apply = (...files: [string, string][]) => {
    const s = new SqlSchema()
    for (const [file, sql] of files) s.applyFile(file, parseDdl(sql, file.includes('postgres') ? 'postgres' : 'mysql'))
    return s.result()
  }

  it('reads column definitions: types as written, NOT NULL, inline keys, generated values', () => {
    const [t] = apply(['a.sql', 'CREATE TABLE t (id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, code CHAR (3) CHARACTER SET ascii NOT NULL UNIQUE, ref INT REFERENCES other(id) ON DELETE CASCADE, created DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP)'])
    expect(columns(t)).toEqual(['id INT UNSIGNED pk generated', 'code CHAR(3) unique', 'ref INT nullable', 'created DATETIME nullable'])
    expect(t.references).toEqual([{ columns: ['ref'], table: 'other', to: ['id'], onDelete: 'CASCADE' }])
  })

  it('reads table constraints and MySQL KEY lines, with their names', () => {
    const [t] = apply(['a.sql', 'CREATE TABLE `t` (`a` INT, `b` INT, CONSTRAINT pk_t PRIMARY KEY (`a`, `b`), UNIQUE KEY `uk_b` (`b`), KEY `ix_ab` (`a`, `b`(10)), CONSTRAINT `fk_b` FOREIGN KEY (`b`) REFERENCES `u` (`id`))'])
    expect(columns(t)).toEqual(['a INT pk', 'b INT pk'])
    expect(t.indexes).toEqual([{ columns: ['b'], unique: true, name: 'uk_b' }, { columns: ['a', 'b'], name: 'ix_ab' }])
    expect(t.references).toEqual([{ columns: ['b'], table: 'u', to: ['id'], name: 'fk_b' }])
  })

  it('follows ALTER TABLE: add, drop, modify, change, rename, keys and indexes', () => {
    const [t] = apply(
      ['V1.sql', 'CREATE TABLE t (id INT PRIMARY KEY, a INT, b INT, c INT)'],
      ['V2.sql', 'ALTER TABLE t ADD COLUMN z INT FIRST, DROP COLUMN c, MODIFY a BIGINT NOT NULL, CHANGE b bb VARCHAR(10), ADD CONSTRAINT fk FOREIGN KEY (bb) REFERENCES u(id), ADD UNIQUE INDEX ux (a); ALTER TABLE t RENAME COLUMN bb TO b2'],
      ['V3.sql', 'ALTER TABLE t DROP FOREIGN KEY fk, DROP INDEX ux, RENAME TO t2'],
      ['V4.sql', 'ALTER TABLE t2 RENAME t3'],
    )
    expect(t.name).toBe('t3')
    expect(columns(t)).toEqual(['z INT nullable', 'id INT pk', 'a BIGINT', 'b2 VARCHAR(10) nullable'])
    expect(t.references).toEqual([])
    expect(t.indexes).toEqual([])
  })

  it('follows PostgreSQL ALTER COLUMN, CREATE INDEX on a quoted table, DROP INDEX without a table, DROP and RENAME TABLE', () => {
    const tables = apply(
      ['postgres/1.sql', 'CREATE TABLE "public"."A" ("id" TEXT NOT NULL, "n" INT, CONSTRAINT "A_pkey" PRIMARY KEY ("id")); CREATE TABLE gone (x INT); CREATE UNIQUE INDEX "A_n_key" ON "A"("n");'],
      ['postgres/2.sql', 'ALTER TABLE "A" ALTER COLUMN "n" SET NOT NULL, ALTER COLUMN "n" TYPE BIGINT USING n::bigint; DROP INDEX IF EXISTS "A_n_key"; DROP TABLE IF EXISTS gone CASCADE;'],
      ['postgres/3.sql', 'ALTER TABLE "A" DROP CONSTRAINT "A_pkey"; RENAME TABLE "A" TO "B";'],
    )
    expect(tables.map(t => `${t.name}: ${columns(t).join(', ')} [${t.indexes.length}]`)).toEqual(['B: id TEXT, n BIGINT [0]'])
  })

  it('skips what is not schema: data, triggers between DELIMITER lines, dollar-quoted bodies, comments', () => {
    const read = ops("-- CREATE TABLE no (x INT);\nINSERT INTO t VALUES ('CREATE TABLE no2 (x INT); x');\nDELIMITER $$\nCREATE TRIGGER x BEFORE INSERT ON t FOR EACH ROW BEGIN SET NEW.a = 1; END$$\nDELIMITER ;\n/* ALTER TABLE t ADD c INT; */\nCREATE TABLE yes (x INT);")
    expect(read.map(o => o.op + ' ' + ('table' in o ? o.table : ''))).toEqual(['create yes'])
    const pg = ops("CREATE FUNCTION f() RETURNS trigger AS $body$ BEGIN CREATE TABLE inner_t (x INT); END $body$ LANGUAGE plpgsql; CREATE TABLE after_fn (x INT);", 'postgres')
    expect(pg.map(o => ('table' in o ? o.table : ''))).toEqual(['after_fn'])
  })

  it('H2 and generated columns: IDENTITY, GENERATED … AS IDENTITY, SERIAL, sequence defaults', () => {
    const [t] = apply(['postgres/a.sql', "CREATE TABLE t (a BIGINT GENERATED BY DEFAULT AS IDENTITY, b BIGSERIAL, c INT DEFAULT nextval('s'::regclass), d UUID DEFAULT gen_random_uuid(), e INT DEFAULT 0)"])
    expect(t.columns.map(c => `${c.name}${c.generated ? '*' : ''}`)).toEqual(['a*', 'b*', 'c*', 'd*', 'e'])
  })

  it('orders Flyway migrations by version as numbers, repeatable ones after, other files by name with numbers as numbers', () => {
    expect(migrationOrder(['m/R__views.sql', 'm/V10__x.sql', 'm/V2__x.sql', 'm/V1_1__x.sql', 'm/V1__x.sql', 'm/U2__undo.sql', 'm/V01_002__x.sql'])).toEqual([
      'm/V1__x.sql',
      'm/V1_1__x.sql',
      'm/V01_002__x.sql',
      'm/V2__x.sql',
      'm/V10__x.sql',
      'm/R__views.sql',
    ])
    expect(migrationOrder(['migrations/10_b/migration.sql', 'migrations/9_a/migration.sql', 'migrations/20240101_c.sql'])).toEqual([
      'migrations/9_a/migration.sql',
      'migrations/10_b/migration.sql',
      'migrations/20240101_c.sql',
    ])
  })
})
