/** A header a code generator writes, in a file's first lines. */
const GENERATED = /@generated\b|\bDO NOT EDIT\b|\b(?:auto-?generated|automatically generated)\b|\bThis file (?:was|is|has been) (?:automatically )?generated\b|\bCode generated by\b/i

const WEB_FRAMEWORKS = ['next', 'vite', 'react-scripts', 'vue', 'svelte', '@sveltejs/kit', 'astro', 'gatsby']

export function detectProject(root: string): Detection {
  const files = listFiles(root)
  const exists = (rel: string) => fs.existsSync(path.join(root, rel))
  const packages = files
    .filter(f => f === 'package.json' || f.endsWith('/package.json'))
    .flatMap(f => {
      const json = readJson(path.join(root, f)) as Package['json'] | undefined
      if (!json) return []
      const deps = new Set(Object.keys({ ...json.dependencies, ...json.devDependencies, ...json.peerDependencies }))
      return [{ prefix: f.slice(0, -'package.json'.length), json, deps }]
    })
    .sort((a, b) => a.prefix.length - b.prefix.length || cmp(a.prefix, b.prefix))
  const allDeps = new Set(packages.flatMap(p => [...p.deps]))

  const stack = [
    ...READ.filter(([re]) => files.some(f => re.test(f))).map(([, label]) => label),
    ...unique(STACK.filter(([dep]) => allDeps.has(dep)).map(([, label]) => label)),
    ...(files.some(f => /(?:^|\/)components\.json$/.test(f)) ? ['shadcn/ui'] : []),
    ...(files.some(f => /(?:^|\/)(?:build\.gradle(?:\.kts)?|pom\.xml)$/.test(f) && /spring-boot|org\.springframework\.boot/.test(read(path.join(root, f)))) ? ['Spring Boot'] : []),
    ...(files.some(f => /(?:^|\/)(?:docker-)?compose(?:\.[\w-]+)?\.ya?ml$/.test(f)) ? ['Docker Compose'] : []),
    ...(files.some(f => /(?:^|\/)Chart\.yaml$/.test(f)) ? ['Helm'] : []),
  ]

  const notes: string[] = []
  const unread = UNREAD.map(([re, label]) => [label, files.filter(f => re.test(f)).length] as const).filter(([, n]) => n > 0)
  if (unread.length) notes.push(`not read (archrift doesn't know these languages): ${unread.map(([l, n]) => `${l} ${n.toLocaleString('en-US')} file${n === 1 ? '' : 's'}`).join(' · ')}`)
  const missing = packages.filter(p => p.deps.size > 0 && !installed(root, p.prefix)).map(p => p.prefix.replace(/\/$/, '') || 'the project folder')
  if (missing.length)
    notes.push(
      `dependencies not installed in ${list(missing)} (no node_modules): the types of the packages they use stay unknown, so calls into them aren't linked. Install them (npm install) and run init again`,
    )

  const tsconfigs = files.filter(f => /(?:^|\/)tsconfig\.json$/.test(f))
  const monorepo = !exists('tsconfig.json') && !exists('jsconfig.json') && tsconfigs.length > 0

  return {
    name: path.basename(path.resolve(root)),
    stack,
    ...(monorepo ? { tsconfig: tsconfigs.sort() } : {}),
    exclude: excludes(root, files, packages),
    tests: testGlobs(root, packages),
    entrypoints: withoutCovered(unique(packages.flatMap(p => entrypointsOf(root, p, exists)).concat(sharedEntrypoints(files, exists)))),
    vendored: vendoredKits(root, files),
    notes,
  }
}

/** The project's files, as git sees them (tracked and untracked, without the ignored), else by walking it. */
function listFiles(root: string): string[] {
  const git = spawnSync('git', ['ls-files', '-co', '--exclude-standard', '-z'], { cwd: root, encoding: 'utf8', maxBuffer: 256 * 2 ** 20 })
  const skip = matcher(DEFAULT_EXCLUDE)
  if (git.status === 0) return git.stdout.split('\0').filter(f => f && !skip(f) && fs.existsSync(path.join(root, f)))
  return walk(root, '', skip, 200_000)
}

function walk(root: string, rel: string, skip: (p: string) => boolean, cap: number, out: string[] = []): string[] {
  let entries: fs.Dirent[]
  try {
    entries = fs.readdirSync(path.join(root, rel), { withFileTypes: true })
  } catch {
    return out
  }
  for (const e of entries.sort((a, b) => cmp(a.name, b.name))) {
    if (out.length >= cap) break
    const p = rel ? `${rel}/${e.name}` : e.name
    if (e.name === '.git' || skip(p) || skip(`${p}/`)) continue
    if (e.isDirectory()) walk(root, p, skip, cap, out)
    else if (e.isFile()) out.push(p)
  }
  return out
}

/** node_modules in the package's folder or one above it, up to the root (workspaces hoist them). */
function installed(root: string, prefix: string): boolean {
  for (let dir = prefix.replace(/\/$/, ''); ; dir = dir.includes('/') ? dir.slice(0, dir.lastIndexOf('/')) : '') {
    if (fs.existsSync(path.join(root, dir, 'node_modules'))) return true
    if (!dir) return false
  }
}

function excludes(root: string, files: string[], packages: Package[]): Detection['exclude'] {
  const out: Detection['exclude'] = []
  const add = (glob: string, why: string) => {
    if (!out.some(e => e.glob === glob)) out.push({ glob, why })
  }
  // what git ignores holds no source: build output, generated clients, caches
  for (const dir of ignoredCodeFolders(root)) add(`${dir}/**`, 'ignored by git')
  // a generator's own output folder, even when it is committed
  for (const f of files.filter(f => f.endsWith('schema.prisma'))) {
    const output = /generator\s+\w+\s*\{[^}]*\boutput\s*=\s*"([^"]+)"/s.exec(read(path.join(root, f)))?.[1]
    if (output) add(`${path.posix.normalize(path.posix.join(path.posix.dirname(f), output))}/**`, 'the Prisma client, generated')
  }
  for (const g of generatedCode(root, files)) add(g, 'generated (its header says so)')
  for (const p of packages)
    if (WEB_FRAMEWORKS.some(d => p.deps.has(d)) && files.some(f => f.startsWith(`${p.prefix}public/`) && JS.test(f))) add(`${p.prefix}public/**`, 'static files the browser loads as they are')
  for (const dir of unique(files.map(f => /^(.*?(?:^|\/)vendor)\//.exec(f)?.[1]).filter((d): d is string => !!d))) add(`${dir}/**`, 'libraries copied in')
  return out
}

/** Folders git ignores that hold code the analysis would otherwise read (node_modules and the like are left out anyway). */
function ignoredCodeFolders(root: string): string[] {
  const git = spawnSync('git', ['ls-files', '-oi', '--exclude-standard', '--directory', '-z'], { cwd: root, encoding: 'utf8', maxBuffer: 64 * 2 ** 20 })
  if (git.status !== 0) return []
  const skip = matcher(DEFAULT_EXCLUDE)
  return git.stdout
    .split('\0')
    .filter(d => d.endsWith('/'))
    .map(d => d.slice(0, -1))
    .filter(d => !skip(d) && !skip(`${d}/`) && walk(root, d, () => false, 2000).some(f => JS.test(f)))
    .sort()
}

/** Files whose header says a tool wrote them, folded into the highest folder that holds nothing else. */
function generatedCode(root: string, files: string[]): string[] {
  const code = files.filter(f => CODE.test(f))
  const generated = new Set(code.filter(f => GENERATED.test(head(path.join(root, f)))))
  if (!generated.size) return []
  const total = new Map<string, number>()
  const made = new Map<string, number>()
  for (const f of code)
    for (const dir of ancestors(f)) {
      total.set(dir, (total.get(dir) ?? 0) + 1)
      if (generated.has(f)) made.set(dir, (made.get(dir) ?? 0) + 1)
    }
  return unique(
    [...generated].sort().map(f => {
      const whole = ancestors(f).find(dir => made.get(dir) === total.get(dir))
      return whole ? `${whole}/**` : f
    }),
  )
}

/** A file's folders, the top one first. */
const ancestors = (file: string) => file.split('/').slice(0, -1).map((_, i, parts) => parts.slice(0, i + 1).join('/'))

function testGlobs(root: string, packages: Package[]): string[] {
  const out = ['**/*.test.*', '**/*.spec.*', '**/__tests__/**', 'test/**', 'tests/**', 'e2e/**']
  for (const p of packages)
    for (const dir of ['test', 'tests', 'e2e', 'cypress', 'playwright']) {
      const glob = `${p.prefix}${dir}/**`
      if (!out.includes(glob) && fs.existsSync(path.join(root, p.prefix, dir))) out.push(glob)
    }
  return out
}

/** What a package's framework, its page, its manifest and its scripts load. */
function entrypointsOf(root: string, p: Package, exists: (rel: string) => boolean): string[] {
  const at = p.prefix
  const out: string[] = []
  const code = (rel: string) => JS.test(rel) && exists(rel)
  if (p.deps.has('next'))
    for (const base of ['', 'src/']) {
      if (exists(`${at}${base}app`))
        out.push(`${at}${base}app/**/{page,layout,template,loading,error,global-error,not-found,default,route,robots,sitemap,manifest,opengraph-image,twitter-image,icon,apple-icon}.{ts,tsx,js,jsx}`)
      if (exists(`${at}${base}pages`)) out.push(`${at}${base}pages/**`)
      for (const name of ['middleware', 'proxy', 'instrumentation']) for (const ext of ['ts', 'js']) if (exists(`${at}${base}${name}.${ext}`)) out.push(`${at}${base}${name}.${ext}`)
    }
  // the scripts an HTML page loads (Vite and the like)
  for (const page of ['index.html', 'src/index.html', 'public/index.html']) {
    if (!exists(`${at}${page}`)) continue
    for (const m of read(path.join(root, at, page)).matchAll(/<script\b[^>]*\bsrc=["']([^"']+)["']/g)) {
      const rel = `${at}${m[1].replace(/^\.?\//, '')}`
      if (code(rel)) out.push(rel)
    }
  }
  const angular = readJson(path.join(root, at, 'angular.json')) as { projects?: Record<string, { architect?: { build?: { options?: Record<string, unknown> } } }> } | undefined
  for (const project of Object.values(angular?.projects ?? {}))
    for (const key of ['main', 'browser', 'server', 'polyfills']) for (const f of strings(project.architect?.build?.options?.[key])) if (code(`${at}${f}`)) out.push(`${at}${f}`)
  if (p.deps.has('@nestjs/core') && exists(`${at}src/main.ts`)) out.push(`${at}src/main.ts`)
  // the manifest's own entries: the source itself, or src/index.* when they point at build output
  for (const f of [p.json.main, p.json.module, p.json.bin, p.json.exports].flatMap(strings).map(f => f.replace(/^\.\//, ''))) {
    if (BUILD_OUTPUT.test(f)) {
      const index = ['ts', 'tsx', 'js', 'mjs'].map(ext => `${at}src/index.${ext}`).find(exists)
      if (index) out.push(index)
    } else if (code(`${at}${f}`)) out.push(`${at}${f}`)
  }
  // files the package's scripts run (node x.mjs, tsx scripts/seed.ts …)
  for (const command of Object.values(p.json.scripts ?? {}))
    for (const token of command.split(/[\s;&|()]+/)) {
      const rel = `${at}${token.replace(/^\.\//, '').replace(/^["']|["']$/g, '')}`
      if (CODE.test(token) && code(rel)) out.push(rel)
    }
  if (fs.readdirSync(path.join(root, at || '.')).some(f => /\.config\.[cm]?[jt]s$/.test(f))) out.push(`${at}*.config.{ts,mts,cts,js,mjs,cjs}`)
  return out
}

/** Entrypoints by convention anywhere: workers, stories, Supabase functions. */
function sharedEntrypoints(files: string[], exists: (rel: string) => boolean): string[] {
  return [
    ...(files.some(f => /\.worker\.[cm]?[jt]s$/.test(f)) ? ['**/*.worker.{ts,js,mjs}'] : []),
    ...(files.some(f => /\.stories\.[jt]sx?$/.test(f)) ? ['**/*.stories.{ts,tsx,js,jsx}'] : []),
    ...(exists('.storybook') ? ['.storybook/**'] : []),
    ...(exists('supabase/functions') ? ['supabase/functions/*/index.ts'] : []),
  ]
}

/** shadcn/ui: components.json names the folder its components are copied into. */
function vendoredKits(root: string, files: string[]): Detection['vendored'] {
  const out: Detection['vendored'] = []
  for (const f of files.filter(f => /(?:^|\/)components\.json$/.test(f))) {
    const at = f.slice(0, -'components.json'.length)
    const json = readJson(path.join(root, f)) as { aliases?: { ui?: string; components?: string } } | undefined
    const alias = json?.aliases?.ui ?? (json?.aliases?.components ? `${json.aliases.components}/ui` : undefined)
    if (!alias) continue
    const dir = resolveAlias(root, at, alias)
    if (dir && fs.existsSync(path.join(root, dir))) out.push({ glob: `${dir}/**`, what: 'shadcn/ui components, copied in' })
  }
  return out
}

/** `@/components/ui` → `src/components/ui`, through the package's tsconfig paths (or `src/` by convention). */
function resolveAlias(root: string, at: string, alias: string): string | undefined {
  if (!alias.startsWith('@') && !alias.startsWith('~')) return `${at}${alias.replace(/^\.\//, '')}`
  for (const name of ['tsconfig.json', 'tsconfig.app.json', 'jsconfig.json']) {
    const file = path.join(root, at, name)
    if (!fs.existsSync(file)) continue
    const config = ts.parseConfigFileTextToJson(file, read(file)).config as { compilerOptions?: { baseUrl?: string; paths?: Record<string, string[]> } } | undefined
    for (const [pattern, targets] of Object.entries(config?.compilerOptions?.paths ?? {})) {
      const prefix = pattern.replace(/\*$/, '')
      if (!alias.startsWith(prefix) || !targets[0]) continue
      const base = config?.compilerOptions?.baseUrl ?? '.'
      return path.posix.normalize(path.posix.join(at || '.', base, targets[0].replace(/\*$/, ''), alias.slice(prefix.length))).replace(/\/$/, '')
    }
  }
  const rest = alias.replace(/^[@~]\/?/, '')
  return fs.existsSync(path.join(root, at, 'src', rest)) ? `${at}src/${rest}` : undefined
}

function readJson(file: string): unknown {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'))
  } catch {
    return undefined
  }
}

function read(file: string): string {
  try {
    return fs.readFileSync(file, 'utf8')
  } catch {
    return ''
  }
}

/** A file's first 512 bytes, where generators put their header. */
function head(file: string): string {
  let fd: number | undefined
  try {
    fd = fs.openSync(file, 'r')
    const buf = Buffer.alloc(512)
    return buf.toString('utf8', 0, fs.readSync(fd, buf, 0, 512, 0))
  } catch {
    return ''
  } finally {
    if (fd !== undefined) fs.closeSync(fd)
  }
}

/** The strings in a manifest field: a string, an array, or nested objects (`exports`, `bin`). */
function strings(v: unknown): string[] {
  if (typeof v === 'string') return [v]
  if (Array.isArray(v)) return v.flatMap(strings)
  if (v && typeof v === 'object') return Object.values(v).flatMap(strings)
  return []
}

const unique = <T>(xs: T[]) => [...new Set(xs)]

/** Single files a glob of the list already covers (`vitest.db.config.ts` beside `*.config.{…}`) go. */
function withoutCovered(entries: string[]): string[] {
  const covered = matcher(entries.filter(e => /[*?{]/.test(e)))
  return entries.filter(e => /[*?{]/.test(e) || !covered(e))
}
const cmp = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0)
const list = (xs: string[]) => (xs.length <= 4 ? xs.join(', ') : `${xs.slice(0, 4).join(', ')} and ${xs.length - 4} more`)
