// What a project is made of, read from its files before the first analysis
// (`archrift init`): the stack, where the code is, what is generated or copied
// in, and what a framework or a script loads, so the first config doesn't have
// to be written by hand. Everything here is a guess from file names and
// manifests; the config it leads to is meant to be read and edited.
import { spawnSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import ts from 'typescript'
import { matcher } from '../core/glob.ts'
import { DEFAULT_EXCLUDE } from './config.ts'

export interface Detection {
  name: string
  /** Languages read, then frameworks and tools, in a stable order. */
  stack: string[]
  /** The tsconfig files when the root has none (a monorepo of packages); otherwise the analyzer's default. */
  tsconfig?: string[]
  /** What to leave out of the analysis, each with the reason. */
  exclude: { glob: string; why: string }[]
  tests: string[]
  /** Files a framework, the HTML page or a script loads: their exports are never dead. */
  entrypoints: string[]
  /** Code copied in from a kit (shadcn/ui): analyzed, but not held to the project's own limits. */
  vendored: { glob: string; what: string }[]
  /** What makes the analysis less than it could be, and how to fix it. */
  notes: string[]
}

interface Package {
  /** '' for the root, else `apps/web/`. */
  prefix: string
  json: { name?: string; main?: unknown; module?: unknown; bin?: unknown; exports?: unknown; scripts?: Record<string, string>; dependencies?: Record<string, string>; devDependencies?: Record<string, string>; peerDependencies?: Record<string, string> }
  deps: Set<string>
}

